"""
main.py — the homelab dashboard: a small web server that shows Pi health and
app status. It only ever reads metrics.db; cron jobs do the writing.

    /            the web page (index.html)
    /api/health  latest Pi reading, written by monitoring/metrics.py
    /api/apps    each app's latest run, written by monitoring/run_app.py
    /docs        interactive API docs, generated by FastAPI

Run locally from the repo root:
    METRICS_DB=/path/to/metrics.db PYTHONPATH=monitoring uvicorn main:app --app-dir dashboard --reload

On the Pi it runs in Docker: see pi-setup.md
"""

import os
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

from fastapi import FastAPI
from fastapi.responses import FileResponse

from health_check import evaluate  # warning thresholds live in monitoring/health_check.py

DB_PATH = Path(os.getenv("METRICS_DB", "metrics.db")).resolve()
INDEX_PAGE = Path(__file__).parent / "index.html"

# metrics.py runs every 5 minutes, so this many seconds without a reading means it has stopped
STALE_AFTER_SECONDS = 15 * 60

app = FastAPI(title="Homelab dashboard")


def query(sql):
    """Runs a query in read-only mode. Returns [] if the database or table doesn't exist yet."""
    try:
        conn = sqlite3.connect(f"{DB_PATH.as_uri()}?mode=ro", uri=True)
    except sqlite3.OperationalError:
        return []
    conn.row_factory = sqlite3.Row
    try:
        return conn.execute(sql).fetchall()
    except sqlite3.OperationalError as e:
        if "no such table" in str(e):
            return []
        raise
    finally:
        conn.close()


def seconds_since(timestamp, until=None):
    """Seconds from an ISO timestamp until another one (or now). Timestamps are stored in UTC."""
    start = datetime.fromisoformat(timestamp)
    if start.tzinfo is None:
        start = start.replace(tzinfo=timezone.utc)
    end = datetime.fromisoformat(until) if until else datetime.now(timezone.utc)
    return round((end - start).total_seconds())


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(INDEX_PAGE)


@app.get("/api/health")
def health():
    rows = query("SELECT * FROM readings ORDER BY id DESC LIMIT 1")
    if not rows:
        return {"status": "NO_DATA", "warnings": [], "reading": None, "age_seconds": None}

    row = rows[0]
    status, warnings = evaluate(row)
    age = seconds_since(row["timestamp"])
    # An old reading says nothing about the Pi right now, however healthy it looks
    if age > STALE_AFTER_SECONDS:
        status = "STALE"
    return {
        "status": status,
        "warnings": warnings,
        "reading": {key: row[key] for key in ("timestamp", "cpu_percent", "mem_percent", "disk_percent", "temp_c")},
        "age_seconds": age,
    }


def run_status(row):
    if row["finished_at"] is None:
        return "UNFINISHED"  # still running, or the Pi lost power or the wrapper was killed mid-run
    return "SUCCESS" if row["exit_code"] == 0 else "FAILED"


@app.get("/api/apps")
def apps():
    rows = query("SELECT * FROM app_runs WHERE id IN (SELECT MAX(id) FROM app_runs GROUP BY app) ORDER BY app")
    return [
        {
            "app": row["app"],
            "status": run_status(row),
            "started_at": row["started_at"],
            "finished_at": row["finished_at"],
            "exit_code": row["exit_code"],
            "duration_seconds": seconds_since(row["started_at"], row["finished_at"]) if row["finished_at"] else None,
        }
        for row in rows
    ]
